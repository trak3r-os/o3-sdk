class IconError(Exception):
    pass


def rows_of(name, art):
    rows = art.strip("\n").split("\n")
    if len(rows) != SIZE or any(len(r) != SIZE or set(r) - set("#.") for r in rows):
        raise IconError("icon '%s' is not %d rows of %d characters from '#' and '.'" % (name, SIZE, SIZE))
    return rows


def encode(rows):
    """32 bytes: two per row, most significant bit leftmost."""
    out = []
    for r in rows:
        bits = int(r.replace("#", "1").replace(".", "0"), 2)
        out += [bits >> 8, bits & 0xFF]
    return out


def all_bytes(icons=None):
    data = []
    for name, art in (icons or ICONS):
        data += encode(rows_of(name, art))
    return data


def camel(name):
    return name[0].upper() + name[1:]


def emit_cpp(icons=None):
    icons = icons or ICONS
    data = all_bytes(icons)
    out = ["// Generated by tools/icon_convert.py -- do not edit, do not commit.",
           "// The icons are drawn in-house (data in that script), GPL-3.0-or-later like the rest of the tree.",
           "// SPDX-License-Identifier: GPL-3.0-or-later",
           "#include <o3sdk/ui/assets.h>",
           "",
           "namespace o3sdk::ui {",
           "namespace {",
           "",
           "// Uploaded with hal::Display::upload(), whose source must be word aligned: declared on the type (ADR 0011).",
           "template <unsigned N>",
           "struct alignas(4) Bitmap {",
           "  std::uint8_t bytes[N];",
           "};",
           "",
           "// %d icons of %dx%d, %d bytes each, in the order of ui::Icon." % (len(icons), SIZE, SIZE, CELL_BYTES),
           "constexpr Bitmap<%d> k_icon_bitmap = {{" % len(data)]
    for j in range(0, len(data), 16):
        out.append("    " + ", ".join("0x%02X" % b for b in data[j:j + 16]) + ",")
    out += ["}};",
            "static_assert(alignof(Bitmap<%d>) >= 4 && sizeof(Bitmap<%d>) >= %d, \"icon bitmap: word aligned, whole\");"
            % (len(data), len(data), len(data)),
            "static_assert(kIconCount == %d, \"ui/assets.h and tools/icon_convert.py disagree on the number of icons\");"
            % len(icons)]
    for i, (name, _) in enumerate(icons):
        out.append("static_assert(static_cast<unsigned>(Icon::%s) == %d, \"icon order: %s\");" % (camel(name), i, name))
    out += ["", "}  // namespace", "",
            "IconBitmap icon_bitmap() noexcept { return IconBitmap{k_icon_bitmap.bytes, %d}; }" % len(data), "",
            "}  // namespace o3sdk::ui", ""]
    return "\n".join(out)


def dump():
    for name, art in ICONS:
        print(name)
        print("\n".join(rows_of(name, art)))
        print()


def self_test():
    failures = []

    def check(cond, what):
        if not cond:
            failures.append(what)

    check(len(ICONS) == 11, "eleven icons")
    check([n for n, _ in ICONS] == ["play", "stop", "record", "loop", "mute", "solo", "lock", "folder", "module",
                                    "midi", "warning"], "icon names and order")
    data = all_bytes()
    check(len(data) == 11 * CELL_BYTES, "size %d" % len(data))
    for i, (name, art) in enumerate(ICONS):
        cell = data[i * CELL_BYTES:(i + 1) * CELL_BYTES]
        ink = sum(bin(b).count("1") for b in cell)
        check(0 < ink < SIZE * SIZE * 3 // 4, "%s has ink, and is not a block (%d px)" % (name, ink))
        check(art.count("#") == ink, "%s: encoding keeps every pixel" % name)
    # Hand-checkable encodings: stop is a block of 10 columns from column 3 (0x1FF8) on rows 3..12.
    stop = data[CELL_BYTES:2 * CELL_BYTES]
    check(stop[:6] == [0, 0, 0, 0, 0, 0] and stop[6:8] == [0x1F, 0xF8] and stop[24:26] == [0x1F, 0xF8]
          and stop[26:] == [0] * 6, "stop encoding %r" % stop)
    play = data[:CELL_BYTES]
    check(play[4:6] == [0x10, 0x00] and play[14:16] == [0x1F, 0xFC], "play encoding")
    for bad in ("x" * 16, "#" * 15):
        try:
            rows_of("bad", "\n".join([bad] * SIZE))
            failures.append("a malformed icon was accepted")
        except IconError:
            pass
    try:
        rows_of("short", "\n".join(["#" * SIZE] * 15))
        failures.append("a short icon was accepted")
    except IconError:
        pass
    text = emit_cpp()
    check(text.count("struct alignas(4) Bitmap") == 1, "emit: aligned bitmap type")
    check("constexpr Bitmap<352> k_icon_bitmap" in text, "emit: one aligned array")
    check("static_assert(alignof(Bitmap<352>) >= 4" in text, "emit: alignment asserted")
    check(text.count("static_assert(static_cast<unsigned>(Icon::") == 11, "emit: the enum order is asserted per icon")
    print("icon_convert self-test: %s" % ("FAILED" if failures else "ok"))
    for f in failures:
        print("  " + f)
    return 1 if failures else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--dump", action="store_true")
    args = parser.parse_args()
    if args.dump:
        dump()
        return 0
    if args.self_test:
        return self_test()
    if not args.out:
        parser.error("--out is required")
    try:
        text = emit_cpp()
    except IconError as e:
        print("icon_convert: %s" % e, file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text() != text:  # keep the mtime when nothing changed
        args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
