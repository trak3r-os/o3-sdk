"""The icon face of the UI: 16 x 16 L1 icons drawn in-house, as data in this script (stdlib only).

OS-003b, docs/specs/OS-003-ui-toolkit.md item 5 and ADR 0010 section 4: eleven icons, no third-party icon set. Each
icon is 16 rows of 16 characters, '#' = ink, '.' = blank. They are converted into one FT81x L1 bitmap of 11 cells
(32 bytes each: 2 bytes per row, most significant bit leftmost, cell n at BITMAP_SOURCE + n * 32, FT81X Series
Programmer's Guide section 4.20), recoloured at draw time with COLOR_RGB like every other L1 bitmap.

The order below is ui::Icon (ui/assets.h); the generated file asserts it, so a reordering on one side fails the build.
The bitmap array is declared word aligned on its type and asserted, as every uploaded bitmap is (ADR 0011).
The generated source goes into the build tree and is not committed.

Usage:
  icon_convert.py --out icon_data.cpp
  icon_convert.py --self-test        (also --dump to print the icons as text)
"""
